from __future__ import annotations

from datetime import UTC, datetime
from uuid import UUID, uuid4

from fastapi import HTTPException, status

from app.models.schemas import (
    ActionRiskLevel,
    ActionStatus,
    IncidentDomain,
    IncidentReport,
    InvestigationReport,
    RecoveryStatus,
    RemediationAction,
    RemediationActionSummary,
    SimulatedMetric,
)


class RemediationService:
    """Manages Human-in-the-Loop (HITL) remediation actions with safe simulated execution."""

    def __init__(self) -> None:
        self._actions: dict[str, RemediationAction] = {}

    def create_action_for_report(
        self, report: InvestigationReport | IncidentReport
    ) -> RemediationAction:
        if isinstance(report, IncidentReport):
            incident_id = report.incident.id
            title = report.incident.title
            domain = report.incident.domain
            evidence_summary = [item.description for item in report.evidence[:5]]
            score = report.risk_score
        else:
            incident_id = report.alert.id
            title = report.alert.title
            domain = IncidentDomain.security
            evidence_summary = [item.description for item in report.evidence[:5]]
            score = report.risk_score

        # Determine risk level
        if score >= 85:
            risk_level = ActionRiskLevel.critical
        elif score >= 60:
            risk_level = ActionRiskLevel.high
        elif score >= 35:
            risk_level = ActionRiskLevel.medium
        else:
            risk_level = ActionRiskLevel.low

        # Primary proposed action from recommendations
        if report.recommended_actions:
            primary_rec = report.recommended_actions[0]
            proposed_action = primary_rec.action
            reasoning = primary_rec.rationale
        else:
            proposed_action = f"Apply default containment and diagnostics for {domain.value} incident."
            reasoning = f"Generated by AegisOps incident response policy based on risk score {score}/100."

        # Root cause hypothesis from findings
        if report.findings:
            root_cause = report.findings[-1].summary
        else:
            root_cause = "Pending multi-agent evidence correlation."

        action = RemediationAction(
            id=uuid4(),
            investigation_id=report.investigation_id,
            incident_id=str(incident_id),
            title=f"Remediation: {title}",
            domain=domain,
            proposed_action=proposed_action,
            root_cause_hypothesis=root_cause,
            reasoning=reasoning,
            supporting_evidence=evidence_summary,
            risk_level=risk_level,
            status=ActionStatus.pending_approval,
            created_at=datetime.now(UTC),
            is_simulated=True,
        )

        self._actions[str(action.id)] = action
        return action

    def list_actions(
        self,
        investigation_id: str | None = None,
        status_filter: ActionStatus | None = None,
    ) -> list[RemediationActionSummary]:
        results: list[RemediationActionSummary] = []
        for action in self._actions.values():
            if investigation_id and str(action.investigation_id) != investigation_id:
                continue
            if status_filter and action.status != status_filter:
                continue
            results.append(
                RemediationActionSummary(
                    id=action.id,
                    investigation_id=action.investigation_id,
                    incident_id=action.incident_id,
                    title=action.title,
                    domain=action.domain,
                    proposed_action=action.proposed_action,
                    risk_level=action.risk_level,
                    status=action.status,
                    recovery_status=action.recovery_status,
                    created_at=action.created_at,
                )
            )
        return sorted(results, key=lambda a: a.created_at, reverse=True)

    def get_action(self, action_id: UUID | str) -> RemediationAction | None:
        return self._actions.get(str(action_id))

    def approve_action(
        self,
        action_id: UUID | str,
        decided_by: str,
        comment: str = "",
        simulate_outcome: str = "success",
    ) -> RemediationAction:
        action = self.get_action(action_id)
        if action is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Remediation action '{action_id}' not found.",
            )

        if action.status == ActionStatus.rejected:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Cannot approve a remediation action that was previously rejected. Rejected actions are permanently blocked.",
            )

        if action.status in (ActionStatus.approved, ActionStatus.executing, ActionStatus.completed):
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Action has already been approved or executed. Duplicate approvals are prevented.",
            )

        if action.status != ActionStatus.pending_approval:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Invalid action state for approval: '{action.status}'.",
            )

        # Transition: pending_approval -> approved -> executing -> completed (or failed)
        now = datetime.now(UTC)
        action.status = ActionStatus.approved
        action.decided_at = now
        action.decided_by = decided_by
        action.decision_comment = comment or "Approved by operator."

        action.status = ActionStatus.executing
        action.execution_timestamp = now

        # Execute safe simulated remediation handler
        self._execute_safe_simulation(action, outcome=simulate_outcome)
        action.status = ActionStatus.completed
        return action

    def reject_action(
        self,
        action_id: UUID | str,
        decided_by: str,
        comment: str = "",
    ) -> RemediationAction:
        action = self.get_action(action_id)
        if action is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Remediation action '{action_id}' not found.",
            )

        if action.status == ActionStatus.rejected:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Action is already rejected.",
            )

        if action.status in (ActionStatus.approved, ActionStatus.executing, ActionStatus.completed):
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Cannot reject an action that has already been approved or executed.",
            )

        if action.status != ActionStatus.pending_approval:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Invalid action state for rejection: '{action.status}'.",
            )

        # Transition: pending_approval -> rejected
        now = datetime.now(UTC)
        action.status = ActionStatus.rejected
        action.decided_at = now
        action.decided_by = decided_by
        action.decision_comment = comment or "Rejected by operator."
        action.execution_result = {
            "is_simulated": True,
            "executed": False,
            "status": "REJECTED_BY_OPERATOR",
            "message": "Action was explicitly rejected. Execution is permanently blocked and will not proceed.",
            "timestamp": now.isoformat(),
        }
        action.recovery_status = RecoveryStatus.pending
        action.recovery_details = "Remediation was rejected; no automated changes were simulated or applied."
        return action

    def _execute_safe_simulation(
        self, action: RemediationAction, outcome: str = "success"
    ) -> None:
        """Deterministic, safe simulated remediation execution and recovery verification.

        DOES NOT run arbitrary shell commands, cloud mutations, or live system modifications.
        Compares explicit simulated measurements before and after the action against documented thresholds.
        """
        now = datetime.now(UTC)
        domain = action.domain
        outcome_clean = outcome.lower().strip()

        if domain == IncidentDomain.production:
            # SRE Production Incident (e.g. 503 errors, high latency)
            if outcome_clean == "failure":
                metrics = [
                    SimulatedMetric(
                        metric_name="checkout_503_error_rate",
                        unit="percent",
                        before_value=28.5,
                        after_value=24.2,
                        target_threshold=1.0,
                        operator="<=",
                        passed=False,
                    ),
                    SimulatedMetric(
                        metric_name="p99_latency",
                        unit="ms",
                        before_value=1450.0,
                        after_value=1380.0,
                        target_threshold=250.0,
                        operator="<=",
                        passed=False,
                    ),
                    SimulatedMetric(
                        metric_name="healthy_service_replicas",
                        unit="count",
                        before_value=2.0,
                        after_value=3.0,
                        target_threshold=8.0,
                        operator=">=",
                        passed=False,
                    ),
                ]
                rec_status = RecoveryStatus.failed
                rec_details = (
                    "DEMO/SIMULATED: Post-action Error Rate (24.2%) exceeded target (<= 1.0%) "
                    "and P99 latency (1380ms) exceeded target (<= 250ms). Simulated rollback failed to restore service health."
                )
            elif outcome_clean == "inconclusive":
                metrics = [
                    SimulatedMetric(
                        metric_name="checkout_503_error_rate",
                        unit="percent",
                        before_value=28.5,
                        after_value=-1.0,
                        target_threshold=1.0,
                        operator="<=",
                        passed=False,
                    ),
                    SimulatedMetric(
                        metric_name="p99_latency",
                        unit="ms",
                        before_value=1450.0,
                        after_value=-1.0,
                        target_threshold=250.0,
                        operator="<=",
                        passed=False,
                    ),
                ]
                rec_status = RecoveryStatus.inconclusive
                rec_details = (
                    "DEMO/SIMULATED: Metrics telemetry stream dropped during simulated rollout. "
                    "Recovery verification is inconclusive due to missing telemetry. Manual verification required."
                )
            else:  # default success
                metrics = [
                    SimulatedMetric(
                        metric_name="checkout_503_error_rate",
                        unit="percent",
                        before_value=28.5,
                        after_value=0.25,
                        target_threshold=1.0,
                        operator="<=",
                        passed=True,
                    ),
                    SimulatedMetric(
                        metric_name="p99_latency",
                        unit="ms",
                        before_value=1450.0,
                        after_value=112.0,
                        target_threshold=250.0,
                        operator="<=",
                        passed=True,
                    ),
                    SimulatedMetric(
                        metric_name="healthy_service_replicas",
                        unit="count",
                        before_value=2.0,
                        after_value=8.0,
                        target_threshold=8.0,
                        operator=">=",
                        passed=True,
                    ),
                ]
                rec_status = RecoveryStatus.verified
                rec_details = (
                    "DEMO/SIMULATED: Recovery verified. Error Rate dropped from 28.5% to 0.25% (<= 1.0%), "
                    "P99 latency decreased from 1450ms to 112ms (<= 250ms), and 8/8 service replicas are healthy."
                )

            command_simulated = "simulated_rollback(service='checkout-api', revision='v2.4.1', replicas=8)"

        elif domain == IncidentDomain.security:
            # Security Incident (e.g. Account Takeover, Impossible Travel)
            if outcome_clean == "failure":
                metrics = [
                    SimulatedMetric(
                        metric_name="active_compromised_sessions",
                        unit="count",
                        before_value=3.0,
                        after_value=2.0,
                        target_threshold=0.0,
                        operator="==",
                        passed=False,
                    ),
                    SimulatedMetric(
                        metric_name="unauthorized_mailbox_rules",
                        unit="count",
                        before_value=1.0,
                        after_value=1.0,
                        target_threshold=0.0,
                        operator="==",
                        passed=False,
                    ),
                ]
                rec_status = RecoveryStatus.failed
                rec_details = "DEMO/SIMULATED: Session revocation failed to terminate all tokens; 2 unauthorized sessions still active."
            elif outcome_clean == "inconclusive":
                metrics = [
                    SimulatedMetric(
                        metric_name="active_compromised_sessions",
                        unit="count",
                        before_value=3.0,
                        after_value=0.0,
                        target_threshold=0.0,
                        operator="==",
                        passed=True,
                    ),
                    SimulatedMetric(
                        metric_name="identity_provider_audit_log_sync",
                        unit="status",
                        before_value=0.0,
                        after_value=0.0,
                        target_threshold=1.0,
                        operator="==",
                        passed=False,
                    ),
                ]
                rec_status = RecoveryStatus.inconclusive
                rec_details = "DEMO/SIMULATED: Token revocation succeeded, but SIEM audit log ingestion delayed by 15 minutes. Verification inconclusive."
            else:
                metrics = [
                    SimulatedMetric(
                        metric_name="active_compromised_sessions",
                        unit="count",
                        before_value=3.0,
                        after_value=0.0,
                        target_threshold=0.0,
                        operator="==",
                        passed=True,
                    ),
                    SimulatedMetric(
                        metric_name="unauthorized_mailbox_rules",
                        unit="count",
                        before_value=1.0,
                        after_value=0.0,
                        target_threshold=0.0,
                        operator="==",
                        passed=True,
                    ),
                    SimulatedMetric(
                        metric_name="mfa_reset_required",
                        unit="status",
                        before_value=0.0,
                        after_value=1.0,
                        target_threshold=1.0,
                        operator="==",
                        passed=True,
                    ),
                ]
                rec_status = RecoveryStatus.verified
                rec_details = (
                    "DEMO/SIMULATED: Security containment verified. All active sessions terminated (0 remaining), "
                    "malicious forwarder mailbox rule purged, and mandatory MFA re-challenge enabled."
                )

            command_simulated = "simulated_identity_containment(user='target_identity', revoke_tokens=True, purge_rules=True)"

        else:
            # Cloud, Data, IT domains
            if outcome_clean == "failure":
                metrics = [
                    SimulatedMetric(
                        metric_name=f"{domain.value}_resource_health",
                        unit="percent",
                        before_value=35.0,
                        after_value=40.0,
                        target_threshold=95.0,
                        operator=">=",
                        passed=False,
                    )
                ]
                rec_status = RecoveryStatus.failed
                rec_details = f"DEMO/SIMULATED: Remediation did not restore {domain.value} health (40% < 95% threshold)."
            elif outcome_clean == "inconclusive":
                metrics = [
                    SimulatedMetric(
                        metric_name=f"{domain.value}_resource_health",
                        unit="percent",
                        before_value=35.0,
                        after_value=-1.0,
                        target_threshold=95.0,
                        operator=">=",
                        passed=False,
                    )
                ]
                rec_status = RecoveryStatus.inconclusive
                rec_details = f"DEMO/SIMULATED: Health probe timeout for {domain.value}. Outcome inconclusive."
            else:
                metrics = [
                    SimulatedMetric(
                        metric_name=f"{domain.value}_resource_health",
                        unit="percent",
                        before_value=35.0,
                        after_value=99.2,
                        target_threshold=95.0,
                        operator=">=",
                        passed=True,
                    )
                ]
                rec_status = RecoveryStatus.verified
                rec_details = f"DEMO/SIMULATED: Recovery verified for {domain.value}. Health restored from 35% to 99.2%."

            command_simulated = f"simulated_domain_remediation(domain='{domain.value}', action='{action.proposed_action}')"

        action.simulated_metrics = metrics
        action.recovery_status = rec_status
        action.recovery_details = rec_details
        action.execution_result = {
            "is_simulated": True,
            "executed": True,
            "status": "SIMULATED_EXECUTION_COMPLETED",
            "command": command_simulated,
            "action_text": action.proposed_action,
            "target_incident": action.incident_id,
            "operator": action.decided_by,
            "comment": action.decision_comment,
            "timestamp": now.isoformat(),
            "simulation_notes": "Safe sandbox execution completed with mock telemetry comparison.",
        }
